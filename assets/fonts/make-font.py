def contours(rows):
    pen_rects = []
    for r, row in enumerate(rows):
        c = 0
        while c < 8:
            if row[c] == '#':
                run = c
                while run < 8 and row[run] == '#': run += 1
                x0, x1 = c * PX, run * PX
                top = ASCENT - r * PX
                bot = ASCENT - (r + 1) * PX
                pen_rects.append((x0, bot, x1, top))
                c = run
            else:
                c += 1
    return pen_rects

names, cmap, glyphs, metrics = ['.notdef'], {}, {}, {}
pen = TTGlyphPen(None)
glyphs['.notdef'] = pen.glyph()
metrics['.notdef'] = (1000, 0)
for i, (ch, rows) in enumerate(sorted(G.items(), key=lambda kv: ord(kv[0]))):
    name = 'uni%04X' % ord(ch)
    names.append(name)
    cmap[ord(ch)] = name
    pen = TTGlyphPen(None)
    for (x0, y0, x1, y1) in contours(rows):
        pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0)); pen.closePath()
    glyphs[name] = pen.glyph()
    metrics[name] = (1000, 0)

fb = FontBuilder(1000, isTTF=True)
fb.setupGlyphOrder(names)
fb.setupCharacterMap(cmap)
fb.setupGlyf(glyphs)
fb.setupHorizontalMetrics(metrics)
fb.setupHorizontalHeader(ascent=ASCENT, descent=-DESCENT)
fb.setupNameTable({
    'familyName': 'Stussy64', 'styleName': 'Regular',
    'fullName': 'Stussy64 Regular', 'psName': 'Stussy64-Regular',
    'copyright': 'An original pixel font made for Stussy Panic. Public domain (CC0).',
    'uniqueFontIdentifier': 'Stussy64-1.0', 'version': 'Version 1.0',
})
fb.setupOS2(sTypoAscender=ASCENT, sTypoDescender=-DESCENT, sTypoLineGap=0,
            usWinAscent=ASCENT, usWinDescent=DESCENT)
